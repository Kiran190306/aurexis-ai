"""
Base agent classes and interfaces for the multi-agent system.
"""
from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional, AsyncGenerator, Callable
from enum import Enum
from pydantic import BaseModel, Field
from datetime import datetime
import uuid


class AgentRole(str, Enum):
    """Agent roles in the multi-agent system."""
    PLANNER = "planner"
    ORCHESTRATOR = "orchestrator"
    RESEARCH = "research"
    CODING = "coding"
    MEMORY = "memory"
    TOOL = "tool"
    REFLECTION = "reflection"


class TaskStatus(str, Enum):
    """Task execution status."""
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"
    RETRYING = "retrying"


class TaskPriority(str, Enum):
    """Task priority levels."""
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class AgentMessage(BaseModel):
    """Message passed between agents."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    sender: str
    receiver: str
    message_type: str
    content: Dict[str, Any]
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    correlation_id: Optional[str] = None


class Task(BaseModel):
    """Task definition for agent execution."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    task_type: str
    description: str
    input_data: Dict[str, Any] = Field(default_factory=dict)
    priority: TaskPriority = TaskPriority.MEDIUM
    status: TaskStatus = TaskStatus.PENDING
    agent_role: AgentRole
    dependencies: List[str] = Field(default_factory=list)
    retry_count: int = 0
    max_retries: int = 3
    timeout_seconds: int = 300
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=datetime.utcnow)
    started_at: Optional[datetime] = None
    completed_at: Optional[datetime] = None
    error_message: Optional[str] = None
    output_data: Optional[Dict[str, Any]] = None


class ExecutionPlan(BaseModel):
    """Execution plan generated by the Planner agent."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    user_request: str
    tasks: List[Task] = Field(default_factory=list)
    estimated_duration_seconds: int = 0
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=datetime.utcnow)


class AgentResponse(BaseModel):
    """Response from an agent."""
    success: bool
    data: Optional[Dict[str, Any]] = None
    error: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)
    execution_time_seconds: float = 0.0


class BaseAgent(ABC):
    """Base class for all specialized agents."""
    
    def __init__(self, agent_id: str, config: Optional[Dict[str, Any]] = None):
        self.agent_id = agent_id
        self.role: AgentRole
        self.config = config or {}
        self._message_handlers: Dict[str, Callable] = {}
    
    @abstractmethod
    async def execute(self, task: Task) -> AgentResponse:
        """Execute a task and return the response."""
        pass
    
    @abstractmethod
    async def initialize(self) -> None:
        """Initialize the agent with any required setup."""
        pass
    
    @abstractmethod
    async def shutdown(self) -> None:
        """Cleanup resources when shutting down."""
        pass
    
    def register_message_handler(self, message_type: str, handler: Callable) -> None:
        """Register a handler for a specific message type."""
        self._message_handlers[message_type] = handler
    
    async def handle_message(self, message: AgentMessage) -> AgentMessage:
        """Handle an incoming message."""
        handler = self._message_handlers.get(message.message_type)
        if handler:
            return await handler(message)  # type: ignore[no-any-return]
        raise ValueError(f"No handler registered for message type: {message.message_type}")
    
    async def send_message(self, receiver: str, message_type: str, content: Dict[str, Any]) -> AgentMessage:
        """Send a message to another agent."""
        return AgentMessage(
            sender=self.agent_id,
            receiver=receiver,
            message_type=message_type,
            content=content
        )
    
    def get_capabilities(self) -> List[str]:
        """Return list of agent capabilities."""
        return []
    
    def get_status(self) -> Dict[str, Any]:
        """Return current agent status."""
        return {
            "agent_id": self.agent_id,
            "role": self.role.value,
            "config": self.config
        }
