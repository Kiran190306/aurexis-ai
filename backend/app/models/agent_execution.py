"""
Database models for multi-agent execution tracking.
"""
from sqlalchemy import Column, Integer, String, Text, DateTime, Boolean, ForeignKey, Enum, JSON, Float
from sqlalchemy.orm import relationship, Mapped, mapped_column
from sqlalchemy.sql import func
from enum import Enum as PyEnum
import uuid

from app.core.database import Base


class ExecutionStatus(PyEnum):
    """Status of agent execution."""
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"
    PAUSED = "paused"


class AgentExecutionPlan(Base):
    """Execution plan generated by Planner agent."""
    __tablename__ = "agent_execution_plans"

    id = Column(Integer, primary_key=True, index=True)
    uuid = Column(String(36), unique=True, default=lambda: str(uuid.uuid4()), index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    conversation_id = Column(Integer, ForeignKey("conversations.id", ondelete="SET NULL"), nullable=True)
    
    # Request
    user_request = Column(Text, nullable=False)
    context = Column(JSON, nullable=True)
    
    # Plan
    plan_data = Column(JSON, nullable=False)  # Full execution plan
    task_count = Column(Integer, default=0)
    estimated_duration_seconds = Column(Integer, default=0)
    
    # Status
    status: Mapped[ExecutionStatus] = mapped_column(Enum(ExecutionStatus), default=ExecutionStatus.PENDING)
    started_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)
    execution_time_seconds = Column(Float, nullable=True)
    
    # Results
    final_output = Column(JSON, nullable=True)
    result_summary = Column(Text, nullable=True)
    
    # Error handling
    error_message = Column(Text, nullable=True)
    error_code = Column(String(50), nullable=True)
    
    # Metadata
    metadata_json = Column(JSON, nullable=True)
    
    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    user = relationship("User", backref="execution_plans")
    conversation = relationship("Conversation", backref="execution_plans")
    execution_logs = relationship("AgentExecutionLog", back_populates="execution_plan", cascade="all, delete-orphan")


class AgentExecutionLog(Base):
    """Execution log for tracking agent operations."""
    __tablename__ = "agent_execution_logs"

    id = Column(Integer, primary_key=True, index=True)
    uuid = Column(String(36), unique=True, default=lambda: str(uuid.uuid4()), index=True)
    execution_plan_id = Column(Integer, ForeignKey("agent_execution_plans.id", ondelete="CASCADE"), nullable=False, index=True)
    agent_id = Column(Integer, ForeignKey("agents.id", ondelete="SET NULL"), nullable=True)
    
    # Task info
    task_id = Column(String(36), nullable=False, index=True)
    task_type = Column(String(50), nullable=False)
    agent_role = Column(String(50), nullable=False)
    
    # Execution
    input_data = Column(JSON, nullable=True)
    output_data = Column(JSON, nullable=True)
    
    # Status
    status: Mapped[ExecutionStatus] = mapped_column(Enum(ExecutionStatus), default=ExecutionStatus.PENDING)
    
    # Timing
    started_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)
    execution_time_seconds = Column(Float, nullable=True)
    
    # Performance
    retry_count = Column(Integer, default=0)
    timeout_seconds = Column(Integer, nullable=True)
    
    # Error handling
    error_message = Column(Text, nullable=True)
    error_code = Column(String(50), nullable=True)
    
    # Dependencies
    depends_on = Column(JSON, nullable=True)  # Array of task IDs
    
    # Metadata
    metadata_json = Column(JSON, nullable=True)
    
    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    execution_plan = relationship("AgentExecutionPlan", back_populates="execution_logs")
    agent = relationship("Agent", backref="execution_logs")


class AgentMetrics(Base):
    """Metrics for agent performance tracking."""
    __tablename__ = "agent_metrics"

    id = Column(Integer, primary_key=True, index=True)
    agent_id = Column(Integer, ForeignKey("agents.id", ondelete="CASCADE"), nullable=False, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    
    # Execution metrics
    total_executions = Column(Integer, default=0)
    successful_executions = Column(Integer, default=0)
    failed_executions = Column(Integer, default=0)
    success_rate = Column(Float, default=0.0)
    
    # Performance metrics
    avg_execution_time_seconds = Column(Float, default=0.0)
    min_execution_time_seconds = Column(Float, nullable=True)
    max_execution_time_seconds = Column(Float, nullable=True)
    total_execution_time_seconds = Column(Float, default=0.0)
    
    # Quality metrics
    avg_quality_score = Column(Float, default=0.0)
    hallucination_count = Column(Integer, default=0)
    
    # Resource metrics
    avg_token_usage = Column(Integer, default=0)
    total_token_usage = Column(Integer, default=0)
    
    # Time period
    period_start = Column(DateTime(timezone=True), nullable=False)
    period_end = Column(DateTime(timezone=True), nullable=False)
    
    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    agent = relationship("Agent", backref="metrics")
    user = relationship("User", backref="agent_metrics")


class AgentEvent(Base):
    """Event log for agent communication and state changes."""
    __tablename__ = "agent_events"

    id = Column(Integer, primary_key=True, index=True)
    uuid = Column(String(36), unique=True, default=lambda: str(uuid.uuid4()), index=True)
    execution_plan_id = Column(Integer, ForeignKey("agent_execution_plans.id", ondelete="SET NULL"), nullable=True, index=True)
    execution_log_id = Column(Integer, ForeignKey("agent_execution_logs.id", ondelete="SET NULL"), nullable=True, index=True)
    agent_id = Column(Integer, ForeignKey("agents.id", ondelete="SET NULL"), nullable=True)
    
    # Event info
    event_type = Column(String(50), nullable=False, index=True)
    event_source = Column(String(50), nullable=False)  # agent_id or system
    event_target = Column(String(50), nullable=True)  # target agent or system
    
    # Event data
    event_data = Column(JSON, nullable=True)
    
    # Message info (for agent communication)
    message_type = Column(String(50), nullable=True)
    message_content = Column(JSON, nullable=True)
    correlation_id = Column(String(36), nullable=True)
    
    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now(), index=True)
    
    # Relationships
    execution_plan = relationship("AgentExecutionPlan", backref="events")
    execution_log = relationship("AgentExecutionLog", backref="events")
    agent = relationship("Agent", backref="events")
